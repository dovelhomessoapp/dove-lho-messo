'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=name=>fs.readFileSync(path.join(root,'www',name),'utf8');
const html=read('index.html'),bridge=read('casa-dolce-casa-bridge.js');
assert.equal(html,read('casa-dolce-casa.html'));
assert.match(html,/dlm-iphone-layout/);assert.match(html,/native-context.js/);
assert.doesNotMatch(html,/<script id="dlm-safe-updates">|rel="manifest"/);
assert.ok(!fs.existsSync(path.join(root,'www/sw.js')));
assert.match(bridge,/dlmStoreDistribution==='app-store'\)throw Error/);
assert.match(bridge,/dlmStoreDistribution!=='app-store'/);
assert.doesNotMatch(bridge,/google-play|versione Android/);
assert.match(bridge,/const redirectTo="https:\/\/dovelhomessoapp.github.io\/dove-lho-messo\/casa-dolce-casa.html"/);
assert.match(bridge,/const redirectUrl="https:\/\/dovelhomessoapp.github.io\/dove-lho-messo\/casa-dolce-casa.html"/);
const context={window:{},document:{documentElement:{dataset:{}}}};
vm.runInNewContext(read('native-context.js'),context);
assert.equal(context.window.dlmStoreDistribution,'app-store');
assert.equal(Object.getOwnPropertyDescriptor(context.window,'dlmStoreDistribution').writable,false);
for(const file of ['vendor/zxing.js','vendor/jsqr.js'])assert.ok(read(file).length>1000);
const config=JSON.parse(fs.readFileSync(path.join(root,'capacitor.config.json'),'utf8'));
assert.equal(config.webDir,'www');assert.ok(!config.server?.url);
console.log('PASS: bundled app, immutable iOS context, store checkout guards, HTTPS email returns and offline scanner libraries');
